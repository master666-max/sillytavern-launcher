"""Sweep platform-specific artifacts out of a node_modules tree.

The rootfs is assembled on the PC, so npm installs win32 artifacts. Pure-JS
packages are cross-platform; anything with native bindings or platform
selector dirs must go. linux-* dirs are kept: the pipeline can target either
arm64-v8a or x86_64 rootfs variants.
"""
import os
import shutil
from pathlib import Path

# Directory names shipped by binary-distributing npm packages (esbuild,
# rollup natives, etc.). Anything matching is dead weight on Android.
PLATFORM_DIRS = {
    "win32-x64", "win32-ia32", "win32-arm64",
    "darwin-x64", "darwin-arm64",
    "sunos-x64", "sunos-arm64",
    "freebsd-x64", "freebsd-arm64",
    "android-arm64", "android-arm", "android-x64",
}


def scan_node_modules(root) -> dict:
    root = Path(root)
    suspect_dirs = []
    dot_node_files = []
    nm = root / "node_modules"
    if not nm.is_dir():
        return {"suspect_dirs": suspect_dirs, "dot_node_files": dot_node_files}
    for dirpath, dirnames, filenames in os.walk(nm):
        dirnames[:] = [d for d in dirnames if d != ".bin"]
        for d in list(dirnames):
            if d in PLATFORM_DIRS:
                suspect_dirs.append(str(Path(dirpath) / d))
        for f in filenames:
            if f.endswith(".node"):
                dot_node_files.append(str(Path(dirpath) / f))
    return {"suspect_dirs": suspect_dirs, "dot_node_files": dot_node_files}


def prune(root, report: dict) -> None:
    for d in report["suspect_dirs"]:
        shutil.rmtree(d, ignore_errors=True)
    for f in report["dot_node_files"]:
        Path(f).unlink(missing_ok=True)


def main():
    import argparse
    import json

    ap = argparse.ArgumentParser()
    ap.add_argument("root", help="directory containing node_modules (usually the ST checkout)")
    ap.add_argument("--prune", action="store_true", help="delete flagged entries")
    ap.add_argument("--report", help="write JSON report to this path")
    args = ap.parse_args()

    report = scan_node_modules(args.root)
    if args.prune:
        prune(args.root, report)
    text = json.dumps(report, indent=1)
    if args.report:
        Path(args.report).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
