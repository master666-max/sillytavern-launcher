import tempfile
import unittest
from pathlib import Path


def _touch(base: Path, rel: str) -> None:
    p = base / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(b"x")


class ScanNodeModulesTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        nm = self.tmp / "node_modules"
        _touch(nm, "@esbuild/win32-x64/esbuild.exe")
        _touch(nm, "@esbuild/linux-arm64/index.js")
        _touch(nm, "fsevents/fsevents.node")
        _touch(nm, "normal-pkg/index.js")

    def test_scan_flags_windows_and_binary_but_not_linux_arm64(self):
        from pipeline.clean_node_modules import scan_node_modules

        report = scan_node_modules(self.tmp)
        suspects = [p.replace("\\", "/") for p in report["suspect_dirs"]]
        self.assertTrue(
            any(p.endswith("node_modules/@esbuild/win32-x64") for p in suspects),
            f"win32-x64 not flagged: {suspects}",
        )
        self.assertFalse(
            any("linux-arm64" in p for p in suspects),
            "linux-arm64 must be kept for the arm64 rootfs",
        )
        self.assertTrue(
            any(p.replace("\\", "/").endswith("fsevents/fsevents.node")
                for p in report["dot_node_files"])
        )
        self.assertFalse(any("normal-pkg" in p for k in report for p in report[k]))

    def test_prune_removes_flagged_only(self):
        from pipeline.clean_node_modules import scan_node_modules, prune

        root = self.tmp
        report = scan_node_modules(root)
        prune(root, report)
        self.assertFalse((root / "node_modules/@esbuild/win32-x64").exists())
        self.assertFalse((root / "node_modules/fsevents/fsevents.node").exists())
        self.assertTrue((root / "node_modules/@esbuild/linux-arm64").exists())
        self.assertTrue((root / "node_modules/normal-pkg/index.js").exists())


if __name__ == "__main__":
    unittest.main()
